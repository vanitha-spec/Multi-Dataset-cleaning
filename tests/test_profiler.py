from src.reader import read_dataset
from src.profiler import profile_dataset


def print_profile(profile, dataset_name):
    """
    Display the important parts of a dataset profile.

    Parameters:
        profile (dict):
            Profile generated by profile_dataset().

        dataset_name (str):
            Name of the dataset being displayed.
    """

    print("\n")
    print("=" * 60)
    print(f"DATASET: {dataset_name}")
    print("=" * 60)

    print("\nRows:")
    print(profile["rows"])

    print("\nColumns:")
    print(profile["columns"])

    print("\nColumn Names:")
    print(profile["column_names"])

    print("\nData Types:")

    for column, dtype in profile["dtypes"].items():
        print(f"  {column}: {dtype}")

    print("\nMissing Values:")

    for column, count in profile["missing_values"].items():
        print(f"  {column}: {count}")

    print("\nDuplicate Rows:")
    print(profile["duplicate_rows"])

    print("\nUnique Values:")

    for column, count in profile["unique_values"].items():
        print(f"  {column}: {count}")

    print("\nValue Counts:")

    for column, counts in profile["value_counts"].items():

        print(f"\n  {column}:")

        for value, count in counts.items():
            print(f"    {repr(value)}: {count}")


def main():
    """
    Read and profile all raw datasets.
    """

    datasets = {
        "customers.csv": "data/raw/customers.csv",
        "orders.csv": "data/raw/orders.csv",
        "products.xlsx": "data/raw/products.xlsx",
        "employees.csv": "data/raw/employees.csv",
    }

    for dataset_name, file_path in datasets.items():

        df = read_dataset(file_path)

        profile = profile_dataset(df)

        print_profile(
            profile,
            dataset_name
        )


if __name__ == "__main__":
    main()